const KUNCI = "pinjamruang_bahasa";
export const BAHASA = ["id", "en"];

let bahasa = "id";
try {
  if (localStorage.getItem(KUNCI) === "en") bahasa = "en";
} catch { /* tanpa localStorage: tetap Indonesia */ }
if (typeof document !== "undefined") document.documentElement.lang = bahasa;

export const ambilBahasa = () => bahasa;

export function setBahasa(b) {
  if (!BAHASA.includes(b)) return;
  bahasa = b;
  try { localStorage.setItem(KUNCI, b); } catch { /* abaikan */ }
  document.documentElement.lang = b;
}

// Locale untuk format tanggal.
export const lokal = () => (bahasa === "en" ? "en-GB" : "id-ID");

// t("server.aktif", { nama: "vm-1" }) mengganti {nama}; nilai array dipilih menurut {n}.
export function t(kunci, isi = {}) {
  let s = teks[bahasa][kunci] ?? teks.id[kunci] ?? kunci;
  if (Array.isArray(s)) s = isi.n === 1 ? s[0] : s[1];
  return s.replace(/\{(\w+)\}/g, (_, k) => isi[k] ?? "");
}

// Terjemahan istilah data; tidak ketemu -> nilai aslinya.
const istilah = (kelompok) => (nilai) => teks[bahasa][`${kelompok}.${nilai}`] ?? nilai;
export const jenisRuangan = istilah("jenisRuangan");
export const kegiatan = istilah("kegiatan");
export const fasilitas = istilah("fasilitas");

// Pesan error dari backend: kalau ada kode (dan terjemahannya), pakai terjemahan sesuai bahasa; kalau tidak, pesan aslinya.
export function pesanGalat(kode, data, bawaan) {
  if (!kode) return bawaan;
  const kunci = "galat." + (kode === "bentrok" && !data?.saran_mulai ? "bentrokTanpaSaran" : kode);
  return teks.id[kunci] ? t(kunci, data || {}) : bawaan;
}

